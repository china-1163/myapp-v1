    function M.setLanguage(code)
        if code == "zh-CN" then language = code; return true end
        return false
    end

    function M.getLanguage()
        return language
    end

    function M.translate(value)
        if type(value) ~= "string" or language ~= "zh-CN" or value == "" then
            return value
        end
        local exact = translations[value]
        if exact then return exact end
        for source, replacement in pairs(prefixes) do
            if value:sub(1, #source) == source then
                return replacement .. value:sub(#source + 1)
            end
        end
        return value
    end

    function M.watchText(instance)
        if not instance then return end
        local function apply()
            local ok, current = pcall(function() return instance.Text end)
            if not ok or type(current) ~= "string" then return end
            local translated = M.translate(current)
            if translated ~= current then
                pcall(function() instance.Text = translated end)
            end
        end
        apply()
        pcall(function()
            instance:GetPropertyChangedSignal("Text"):Connect(apply)
        end)
    end

    function M.watchPlaceholder(instance)
        if not instance then return end
        local function apply()
            local ok, current = pcall(function() return instance.PlaceholderText end)
            if not ok or type(current) ~= "string" then return end
            local translated = M.translate(current)
            if translated ~= current then
                pcall(function() instance.PlaceholderText = translated end)
            end
        end
        apply()
        pcall(function()
            instance:GetPropertyChangedSignal("PlaceholderText"):Connect(apply)
        end)
    end

